// Renders echo's icon from exact geometry: a dot and the two rings of its echo,
// the outer one fading. Same visual language as muse and Caller — background
// gradient, 70px round-capped stroke, r=42 dot in #6eb5ff — so the three read as a set.
//
//   swift scripts/make-icon.swift      (run from repo root)
//
// Outputs assets/icon-source.svg, icon.png, icon.icns, trayTemplate.png, trayTemplate@2x.png.
import AppKit

let assets = URL(fileURLWithPath: "assets")

// MARK: geometry (1024 canvas, y down)

let stroke: CGFloat = 70
let dotR: CGFloat = 42
let rings: [(radius: CGFloat, alpha: CGFloat)] = [(150, 1), (262, 0.38)]  // each echo quieter than the last
let span: CGFloat = 48             // half the sweep of each ring, in degrees from the +x axis

// Center the group (dot left edge .. outer ring right edge) on the canvas.
let groupLeft = -dotR
let groupRight = rings.last!.radius + stroke / 2
let cx = 512 - (groupLeft + groupRight) / 2
let cy: CGFloat = 512

func rad(_ d: CGFloat) -> CGFloat { d * .pi / 180 }
func f(_ v: CGFloat) -> String { String(format: "%.1f", v) }

// MARK: SVG (source of truth for Figma tweaks)

let arcs = rings.map { ring -> String in
    let x = cx + ring.radius * cos(rad(span))
    let y0 = cy - ring.radius * sin(rad(span)), y1 = cy + ring.radius * sin(rad(span))
    return """
      <path d="M\(f(x)) \(f(y0)) A\(f(ring.radius)) \(f(ring.radius)) 0 0 1 \(f(x)) \(f(y1))"
            fill="none" stroke="#1c1c1e" stroke-opacity="\(ring.alpha)" stroke-width="\(f(stroke))" stroke-linecap="round"/>
    """
}.joined(separator: "\n")
let svg = """
<?xml version="1.0" encoding="UTF-8"?>
<!--
  echo app icon — generated by scripts/make-icon.swift (edit the geometry there).
  Sibling of muse's and Caller's icons: same bg, stroke weight and accent dot.
    • bg    — full-bleed light gradient (macOS applies the squircle)
    • dot   — the blue accent: the source
    • rings — its echo, the outer one fainter
-->
<svg width="1024" height="1024" viewBox="0 0 1024 1024" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="bgGrad" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#fbfbfd"/>
      <stop offset="1" stop-color="#e9e9ee"/>
    </linearGradient>
  </defs>
  <rect id="bg" width="1024" height="1024" fill="url(#bgGrad)"/>
  <circle id="dot" cx="\(f(cx))" cy="\(f(cy))" r="\(f(dotR))" fill="#6eb5ff"/>
\(arcs)
</svg>

"""
try! svg.write(to: assets.appendingPathComponent("icon-source.svg"), atomically: true, encoding: .utf8)

// MARK: raster

func color(_ hex: UInt32, _ alpha: CGFloat = 1) -> CGColor {
    CGColor(srgbRed: CGFloat(hex >> 16 & 0xff) / 255, green: CGFloat(hex >> 8 & 0xff) / 255,
            blue: CGFloat(hex & 0xff) / 255, alpha: alpha)
}

/// Draws into a `px`-sized bitmap. `template`: black mark on transparent, sized for the menu bar.
func render(px: Int, template: Bool) -> Data {
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: px, pixelsHigh: px, bitsPerSample: 8,
                               samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                               colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
    let ctx = NSGraphicsContext(bitmapImageRep: rep)!.cgContext
    let s = CGFloat(px) / 1024
    ctx.scaleBy(x: s, y: s)
    // Flip to the SVG's y-down space.
    ctx.translateBy(x: 0, y: 1024)
    ctx.scaleBy(x: 1, y: -1)

    var st = stroke, dr = dotR, k: CGFloat = 1, x0 = cx
    if template {
        // At 18pt the mark must fill the frame and the stroke gets relatively heavier.
        let height = 2 * rings.last!.radius * sin(rad(span)) + stroke
        k = 1024 / max(height, groupRight - groupLeft) * 0.9
        st = stroke * k * 1.2; dr = dotR * k * 1.25
        x0 = 512 - (-dr + rings.last!.radius * k + st / 2) / 2
    } else {
        let bg = CGGradient(colorsSpace: CGColorSpace(name: CGColorSpace.sRGB),
                            colors: [color(0xfbfbfd), color(0xe9e9ee)] as CFArray, locations: [0, 1])!
        ctx.drawLinearGradient(bg, start: CGPoint(x: 0, y: 0), end: CGPoint(x: 0, y: 1024), options: [])
    }

    ctx.setFillColor(template ? CGColor(gray: 0, alpha: 1) : color(0x6eb5ff))
    ctx.fillEllipse(in: CGRect(x: x0 - dr, y: cy - dr, width: dr * 2, height: dr * 2))

    ctx.setLineWidth(st)
    ctx.setLineCap(.round)
    for ring in rings {
        // Template images keep alpha, so the fading echo survives in the menu bar (a bit stronger to stay legible).
        ctx.setStrokeColor(template ? CGColor(gray: 0, alpha: ring.alpha == 1 ? 1 : 0.5) : color(0x1c1c1e, ring.alpha))
        ctx.addArc(center: CGPoint(x: x0, y: cy), radius: ring.radius * k,
                   startAngle: rad(-span), endAngle: rad(span), clockwise: false)
        ctx.strokePath()
    }
    return rep.representation(using: .png, properties: [:])!
}

try! render(px: 1024, template: false).write(to: assets.appendingPathComponent("icon.png"))
try! render(px: 18, template: true).write(to: assets.appendingPathComponent("trayTemplate.png"))
try! render(px: 36, template: true).write(to: assets.appendingPathComponent("trayTemplate@2x.png"))

// .icns via iconutil
let iconset = FileManager.default.temporaryDirectory.appendingPathComponent("echo.iconset")
try? FileManager.default.removeItem(at: iconset)
try! FileManager.default.createDirectory(at: iconset, withIntermediateDirectories: true)
for base in [16, 32, 128, 256, 512] {
    try! render(px: base, template: false).write(to: iconset.appendingPathComponent("icon_\(base)x\(base).png"))
    try! render(px: base * 2, template: false).write(to: iconset.appendingPathComponent("icon_\(base)x\(base)@2x.png"))
}
let p = Process()
p.executableURL = URL(fileURLWithPath: "/usr/bin/iconutil")
p.arguments = ["-c", "icns", iconset.path, "-o", assets.appendingPathComponent("icon.icns").path]
try! p.run()
p.waitUntilExit()
print(p.terminationStatus == 0 ? "wrote assets/icon.{png,icns,svg}, trayTemplate{,@2x}.png" : "iconutil failed")
