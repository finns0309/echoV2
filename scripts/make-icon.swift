// Renders echo's icon from exact geometry: a half sun and its reflection, the
// reflection broken into strips that fade as they go down. echo doesn't shine on
// its own; it shows what the other apps are saying.
// Same frame as muse's and Memoir's icons (an 824 rounded square, rx 186, on the
// 1024 canvas, with a soft drop shadow and a hairline rim), so they read as a set:
// muse is ivory, Memoir sky blue, echo olive.
//
//   swift scripts/make-icon.swift      (run from repo root)
//
// Outputs assets/icon-source.svg, icon.png, icon.icns, trayTemplate.png, trayTemplate@2x.png.
import AppKit

let assets = URL(fileURLWithPath: "assets")

// MARK: geometry (y down)

struct Strip { let y: CGFloat; let width: CGFloat; let alpha: CGFloat }
/// A half disc standing on `horizon`, with strips of its reflection below it.
struct Mark { let cx: CGFloat; let horizon: CGFloat; let r: CGFloat; let stripHeight: CGFloat; let strips: [Strip] }

// App icon, 1024 canvas. The strips follow the disc's chords, each fainter than the last.
let appMark = Mark(cx: 512, horizon: 515, r: 196, stripHeight: 34, strips: [
    Strip(y: 547, width: 380, alpha: 0.55),
    Strip(y: 609, width: 323, alpha: 0.34),
    Strip(y: 671, width: 184, alpha: 0.18),
])
// Menu bar, 36px canvas (the @2x image; @1x is the same at half scale).
// Two heavier strips instead of three, on whole pixels, so it holds at 18pt.
let trayMark = Mark(cx: 18, horizon: 18, r: 11.5, stripHeight: 3, strips: [
    Strip(y: 21, width: 22, alpha: 0.6),
    Strip(y: 27, width: 16.4, alpha: 0.35),
])

let frame = CGRect(x: 100, y: 100, width: 824, height: 824)
let corner: CGFloat = 186
let olive: (top: UInt32, bottom: UInt32) = (0x8a9e6e, 0x6c8051)
let ivory: UInt32 = 0xfaf9f5

func f(_ v: CGFloat) -> String { String(format: "%g", Double((v * 10).rounded() / 10)) }
func hex(_ c: UInt32) -> String { String(format: "#%06X", c) }

// MARK: SVG (source of truth for Figma tweaks)

let m = appMark
let strips = m.strips.map { s in
    "    <rect x=\"\(f(m.cx - s.width / 2))\" y=\"\(f(s.y))\" width=\"\(f(s.width))\" height=\"\(f(m.stripHeight))\" rx=\"\(f(m.stripHeight / 2))\" fill-opacity=\"\(s.alpha)\"/>"
}.joined(separator: "\n")
let svg = """
<?xml version="1.0" encoding="UTF-8"?>
<!--
  echo app icon: generated by scripts/make-icon.swift (edit the geometry there).
  Sibling of muse's and Memoir's icons: same rounded square, shadow and rim.
    • bg         olive, a touch darker at the bottom
    • sun        a half disc standing on the horizon
    • reflection its image in the water, in strips that fade as they go down
-->
<svg width="1024" height="1024" viewBox="0 0 1024 1024" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="\(hex(olive.top))"/>
      <stop offset="1" stop-color="\(hex(olive.bottom))"/>
    </linearGradient>
    <filter id="drop" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="14"/>
      <feOffset dy="10"/>
      <feComponentTransfer><feFuncA type="linear" slope="0.22"/></feComponentTransfer>
      <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
  </defs>

  <g filter="url(#drop)">
    <rect x="\(f(frame.minX))" y="\(f(frame.minY))" width="\(f(frame.width))" height="\(f(frame.height))" rx="\(f(corner))" fill="url(#bg)"/>
  </g>
  <rect x="\(f(frame.minX + 0.5))" y="\(f(frame.minY + 0.5))" width="\(f(frame.width - 1))" height="\(f(frame.height - 1))" rx="\(f(corner - 0.5))" fill="none" stroke="#000" stroke-opacity="0.08"/>

  <g fill="\(hex(ivory))">
    <path d="M\(f(m.cx - m.r)) \(f(m.horizon)) A\(f(m.r)) \(f(m.r)) 0 0 1 \(f(m.cx + m.r)) \(f(m.horizon)) Z"/>
\(strips)
  </g>
</svg>

"""
try! svg.write(to: assets.appendingPathComponent("icon-source.svg"), atomically: true, encoding: .utf8)

// MARK: raster

func color(_ hex: UInt32, _ alpha: CGFloat = 1) -> CGColor {
    CGColor(srgbRed: CGFloat(hex >> 16 & 0xff) / 255, green: CGFloat(hex >> 8 & 0xff) / 255,
            blue: CGFloat(hex & 0xff) / 255, alpha: alpha)
}

func draw(_ m: Mark, in ctx: CGContext, ink: (CGFloat) -> CGColor) {
    ctx.setFillColor(ink(1))
    ctx.move(to: CGPoint(x: m.cx - m.r, y: m.horizon))
    ctx.addArc(center: CGPoint(x: m.cx, y: m.horizon), radius: m.r, startAngle: .pi, endAngle: 2 * .pi, clockwise: false)
    ctx.closePath()
    ctx.fillPath()
    for s in m.strips {
        ctx.setFillColor(ink(s.alpha))
        let rect = CGRect(x: m.cx - s.width / 2, y: s.y, width: s.width, height: m.stripHeight)
        ctx.addPath(CGPath(roundedRect: rect, cornerWidth: m.stripHeight / 2, cornerHeight: m.stripHeight / 2, transform: nil))
        ctx.fillPath()
    }
}

/// Draws into a `px`-sized bitmap. `template`: black mark on transparent, for the menu bar.
func render(px: Int, template: Bool) -> Data {
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: px, pixelsHigh: px, bitsPerSample: 8,
                               samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                               colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
    let ctx = NSGraphicsContext(bitmapImageRep: rep)!.cgContext
    let canvas: CGFloat = template ? 36 : 1024
    let s = CGFloat(px) / canvas
    ctx.scaleBy(x: s, y: s)
    // Flip to the SVG's y-down space.
    ctx.translateBy(x: 0, y: canvas)
    ctx.scaleBy(x: 1, y: -1)

    if template {
        // Template images keep alpha, so the fading reflection survives in the menu bar.
        draw(trayMark, in: ctx) { CGColor(gray: 0, alpha: $0) }
        return rep.representation(using: .png, properties: [:])!
    }

    let squircle = CGPath(roundedRect: frame, cornerWidth: corner, cornerHeight: corner, transform: nil)
    // Shadow offset and blur live in device space (y up), so they neither flip nor scale with the CTM.
    ctx.saveGState()
    ctx.setShadow(offset: CGSize(width: 0, height: -10 * s), blur: 28 * s, color: CGColor(gray: 0, alpha: 0.22))
    ctx.setFillColor(color(olive.bottom))
    ctx.addPath(squircle)
    ctx.fillPath()
    ctx.restoreGState()

    ctx.saveGState()
    ctx.addPath(squircle)
    ctx.clip()
    let bg = CGGradient(colorsSpace: CGColorSpace(name: CGColorSpace.sRGB),
                        colors: [color(olive.top), color(olive.bottom)] as CFArray, locations: [0, 1])!
    ctx.drawLinearGradient(bg, start: CGPoint(x: 0, y: frame.minY), end: CGPoint(x: 0, y: frame.maxY), options: [])
    ctx.restoreGState()

    ctx.setStrokeColor(CGColor(gray: 0, alpha: 0.08))
    ctx.setLineWidth(1)
    ctx.addPath(CGPath(roundedRect: frame.insetBy(dx: 0.5, dy: 0.5), cornerWidth: corner - 0.5, cornerHeight: corner - 0.5, transform: nil))
    ctx.strokePath()

    draw(appMark, in: ctx) { color(ivory, $0) }
    return rep.representation(using: .png, properties: [:])!
}

try! render(px: 1024, template: false).write(to: assets.appendingPathComponent("icon.png"))
try! render(px: 18, template: true).write(to: assets.appendingPathComponent("trayTemplate.png"))
try! render(px: 36, template: true).write(to: assets.appendingPathComponent("trayTemplate@2x.png"))

// .icns via iconutil
let iconset = FileManager.default.temporaryDirectory.appendingPathComponent("echo.iconset")
try? FileManager.default.removeItem(at: iconset)
try! FileManager.default.createDirectory(at: iconset, withIntermediateDirectories: true)
for base in [16, 32, 128, 256, 512] {
    try! render(px: base, template: false).write(to: iconset.appendingPathComponent("icon_\(base)x\(base).png"))
    try! render(px: base * 2, template: false).write(to: iconset.appendingPathComponent("icon_\(base)x\(base)@2x.png"))
}
let p = Process()
p.executableURL = URL(fileURLWithPath: "/usr/bin/iconutil")
p.arguments = ["-c", "icns", iconset.path, "-o", assets.appendingPathComponent("icon.icns").path]
try! p.run()
p.waitUntilExit()
print(p.terminationStatus == 0 ? "wrote assets/icon.{png,icns,svg}, trayTemplate{,@2x}.png" : "iconutil failed")
